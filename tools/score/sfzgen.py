    with open(path, 'w') as f:
        f.write(out)
    # The sample set's bass is stretched 10-20 cents flat. Pull every keycenter
    # up to A3 back toward equal temperament (mean of partials 1 and 2), so the
    # piano's left hand does not beat against the ET contrabass and sub.
    from sampler import Instrument
    inst = Instrument(path)
    corr = {}
    for kc in sorted(set(r['center'] for r in inst.regions if r['trigger'] == 'attack' and r['center'] <= 57)):
        x = inst.render([(0.0, 2.0, kc, 70)], SR_ * 3)
        m = x.mean(1)
        on = int(np.argmax(np.abs(m) > 0.05 * np.abs(m).max()))
        seg = m[on + int(0.3 * SR_):on + int(1.8 * SR_)]
        N = 1 << 19
        X = np.abs(np.fft.rfft(seg * np.hanning(len(seg)), N))
        fr = np.fft.rfftfreq(N, 1 / SR_)
        devs = []
        for h in (1, 2):
            f0 = A.hz(kc) * h
            sel = (fr > f0 * 2 ** (-0.5 / 12)) & (fr < f0 * 2 ** (0.5 / 12))
            devs.append(1200 * np.log2(fr[np.argmax(X * sel)] / f0))
        d = float(np.mean(devs))
        if abs(d) > 4:
            corr[kc] = int(round(-d))

    def fix_region(m):
        line = m.group(0)
        kc = re.search(r'pitch_keycenter=(\d+)', line)
        if not kc or int(kc.group(1)) not in corr:
            return line
        c = corr[int(kc.group(1))]
        t = re.search(r'tune=(-?\d+)', line)
        if t:
            return line.replace(t.group(0), 'tune=%d' % (int(t.group(1)) + c))
        return line.replace('pitch_keycenter=', 'tune=%d pitch_keycenter=' % c, 1)
    out = re.sub(r'<region>[^\n]*', fix_region, out)
    with open(path, 'w') as f:
        f.write(out)
    META['piano'] = {'gain_db': G, 'bass_tune_correction_cents': corr}

