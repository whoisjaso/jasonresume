"""Build SFZ instruments from the CC0 VSCO-2-CE and VCSL sample folders (which
ship as WAVs named by note), plus a wrapper for the Salamander Grand Piano.

Every sample is measured before it is mapped:
  * root pitch: harmonic-sum f0 estimate; the octave convention of each
    library is confirmed by pitchcheck.py and per-sample tuning error is
    corrected with tune= when the estimate is confident (|err| < 40 cents)
  * leading silence trimmed with offset= (onset at -50 dB re peak, minus 2 ms)
  * perceived attack delay (onset -> -6 dB of the early sustain level) is
    written to instruments.json so the composer can pull notes early
  * for crescendo one-shots, the time of the climax is stored likewise
"""
