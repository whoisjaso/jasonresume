NOTE = {'C': 0, 'D': 2, 'E': 4, 'F': 5, 'G': 7, 'A': 9, 'B': 11}


def parse_note(name, octave_shift):
    m = re.search(r'(?<![A-Za-z])([A-G])(#|b)?(-?\d)(?!\d)', name)
    n = NOTE[m.group(1)] + {'#': 1, 'b': -1, None: 0}[m.group(2)]
    return 12 * (int(m.group(3)) + 1 + octave_shift) + n


def analyse(path, expect_midi=None, measure_pitch=True, skip=0.25):
    x, sr = sf.read(path, always_2d=True)
    mono = x.mean(1)
    pk = np.abs(mono).max() + 1e-12
    env = np.abs(mono)
    on = int(np.argmax(env > pk * 10 ** (-50 / 20)))
    off = max(0, on - int(0.002 * sr))
    # smoothed RMS envelope (10 ms)
    w = int(0.01 * sr)
    rms = np.sqrt(np.convolve(mono ** 2, np.ones(w) / w, mode='same'))
    early = rms[on + int(0.3 * sr):on + int(1.2 * sr)]
    sus = np.median(early) if len(early) else rms.max()
    reach = np.argmax(rms[on:] > sus * 0.5)
    attack = reach / sr
    peak_t = (np.argmax(rms) - on) / sr
    tune = 0
    if measure_pitch and expect_midi is not None:
        # energy centroid of partials 1-3 (each within +-50 cents of its
        # expected frequency), over 1 s windows after the attack: robust to
        # vibrato and ensemble spread, unlike a single FFT peak
        f0 = 440 * 2 ** ((expect_midi - 69) / 12)
        ests, wts = [], []
        a0 = on + int(max(0.05, attack + 0.15) * sr)
        for k in range(3):
            seg = mono[a0 + k * int(0.7 * sr):a0 + k * int(0.7 * sr) + int(1.0 * sr)]
            if len(seg) < 0.25 * sr:
                break
            N = 1 << 18
            X = np.abs(np.fft.rfft(seg * np.hanning(len(seg)), N)) ** 2
            fr = np.fft.rfftfreq(N, 1 / sr)
            tot = X.max()
            for h in (1, 2, 3):
                sel = (fr > f0 * h * 2 ** (-0.5 / 12)) & (fr < f0 * h * 2 ** (0.5 / 12))
                if tot <= 0 or not sel.any() or X[sel].max() < tot * 1e-3:
                    continue
                c = (X[sel] * fr[sel]).sum() / X[sel].sum()
                ests.append(1200 * np.log2(c / (f0 * h)))
                wts.append(X[sel].sum())
        if ests:
            o = np.argsort(ests)
            cw = np.cumsum(np.array(wts)[o])
            err = np.array(ests)[o][np.searchsorted(cw, cw[-1] / 2)]
            if 3 <= abs(err) < 45:
                tune = int(round(-err))
    return {'offset': off, 'attack': attack, 'peak_t': peak_t, 'len': (len(mono) - off) / sr,
            'tune': tune, 'sr': sr, 'peak': float(pk)}


def keyranges(roots, lo_ext=5, hi_ext=5):
    roots = sorted(set(roots))
    out = {}
    for i, r in enumerate(roots):
        lo = roots[i - 1] + (r - roots[i - 1]) // 2 + 1 if i > 0 else r - lo_ext
        hi = r + (roots[i + 1] - r) // 2 if i < len(roots) - 1 else r + hi_ext
        out[r] = (max(0, lo), min(127, hi))
    return out


def write_sfz(name, header, regions, meta):
    path = os.path.join(A.SFZ_DIR, name + '.sfz')
    with open(path, 'w') as f:
        f.write('// generated by sfzgen.py\n')
        f.write(header + '\n')
        for r in regions:
            f.write('<region> ' + ' '.join('%s=%s' % kv for kv in r.items()) + '\n')
    META[name] = meta
    return path


def layered(name, folder, pattern, layer_of, octave_shift, header, vel_layers, xfade=True,
            measure_pitch=True, extra=None, fixed_roots=None):
    """Generic note-named multisample: layer_of(filename) -> layer index (0 = softest)."""
    files = sorted(glob.glob(os.path.join(folder, pattern)))
    by_layer = {}
    info = {}
    for fn in files:
        b = os.path.basename(fn)
        L = layer_of(b)
        if L is None:
            continue
        midi = fixed_roots[b] if fixed_roots else parse_note(b, octave_shift)
        an = analyse(fn, midi, measure_pitch)
        by_layer.setdefault(L, {}).setdefault(midi, []).append((fn, an))
        info[b] = dict(an, midi=midi, layer=L)
    nl = len(vel_layers)
    regions = []
    for L in sorted(by_layer):
        kr = keyranges(list(by_layer[L].keys()))
        lo_v, hi_v = vel_layers[L]
        for midi, lst in sorted(by_layer[L].items()):
            for k, (fn, an) in enumerate(lst):
                r = {'sample': fn.replace(' ', '\\ ') if False else fn, 'pitch_keycenter': midi,
                     'lokey': kr[midi][0], 'hikey': kr[midi][1], 'offset': an['offset']}
                if an['tune']:
                    r['tune'] = an['tune']
                if xfade and nl > 1:
                    # equal-power velocity crossfade between neighbouring layers
                    if L > 0:
                        r['xfin_lovel'] = vel_layers[L - 1][1] - 12
                        r['xfin_hivel'] = lo_v + 12
                        r['lovel'] = vel_layers[L - 1][1] - 12
                    else:
                        r['lovel'] = 1
                    if L < nl - 1:
                        r['xfout_lovel'] = hi_v - 12
                        r['xfout_hivel'] = vel_layers[L + 1][0] + 12
                        r['hivel'] = vel_layers[L + 1][0] + 12
                    else:
                        r['hivel'] = 127
                else:
                    r['lovel'], r['hivel'] = lo_v, hi_v
                if len(lst) > 1:
                    r['seq_length'] = len(lst)
                    r['seq_position'] = k + 1
                if extra:
                    r.update(extra(os.path.basename(fn), an))
                regions.append(r)
    # sfz sample paths with spaces: sfizz accepts them to end of line only if
    # sample= is the last opcode, so move it last
    regions = [dict([(k, v) for k, v in r.items() if k != 'sample'] + [('sample', r['sample'])]) for r in regions]
    return write_sfz(name, header, regions, info)


def lay(tags):
    def f(b):
        for i, t in enumerate(tags):
            if re.search(t, b):
                return i
        return None
    return f


